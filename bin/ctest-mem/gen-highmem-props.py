#!/usr/bin/env python3
"""Emit CTest scheduling properties for memory-heavy tests.

Reads a CSV of "name,peakMB,exit" rows (produced by measure-test-rss.sh),
keeps the worst peak seen per test, and emits a .cmake file that tags every
test whose peak exceeds --threshold-mb so CTest will not over-subscribe RAM.

Two policies:
  budget  (default) -> RESOURCE_GROUPS "mem:<ceil(GB)>"  (co-schedule within a
                       runner RAM budget; pass --resource-spec-file at ctest time)
  solo              -> RUN_SERIAL ON                      (the test runs alone)

The generated block is guarded by ITK_CTEST_MEMORY_BUDGET so a normal `ctest`
run (no resource-spec file) is unaffected -- RESOURCE_GROUPS without a spec
file is a hard CTest error, so it must stay opt-in.
"""
import argparse
import csv
import math
import sys


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", help="peaks CSV from measure-test-rss.sh")
    ap.add_argument("-o", "--output", default="-", help="output .cmake (default stdout)")
    ap.add_argument("--threshold-mb", type=int, default=3072,
                    help="flag tests peaking above this (default 3072 = 3 GB)")
    ap.add_argument("--policy", choices=("budget", "solo"), default="budget")
    args = ap.parse_args()

    worst: dict[str, int] = {}
    with open(args.csv, newline="") as fh:
        for row in csv.reader(fh):
            if len(row) < 2:
                continue
            name, peak = row[0].strip(), row[1].strip()
            if not peak.isdigit():
                continue
            worst[name] = max(worst.get(name, 0), int(peak))

    heavy = sorted((n, mb) for n, mb in worst.items() if mb > args.threshold_mb)

    lines = [
        "# Generated by gen-highmem-props.py -- do not edit by hand.",
        f"# Tests peaking above {args.threshold_mb} MB; policy={args.policy}.",
        "if(ITK_CTEST_MEMORY_BUDGET)",
    ]
    if not heavy:
        lines.append(f"  # No test exceeded {args.threshold_mb} MB in the profiling pass.")
    for name, mb in heavy:
        if args.policy == "solo":
            lines.append(f'  set_tests_properties({name} PROPERTIES RUN_SERIAL ON) # {mb} MB')
        else:
            gb = math.ceil(mb / 1024)
            lines.append(
                f'  set_property(TEST {name} APPEND PROPERTY RESOURCE_GROUPS "mem:{gb}") # {mb} MB')
    lines.append("endif()")
    text = "\n".join(lines) + "\n"

    out = sys.stdout if args.output == "-" else open(args.output, "w")
    out.write(text)
    if out is not sys.stdout:
        out.close()
    sys.stderr.write(f"{len(heavy)} test(s) over {args.threshold_mb} MB\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
